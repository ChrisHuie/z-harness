# An announcement of imminent action BY ME, anchored to the TAIL of the final
# message. The same words mid-message are ordinary narration of work that then
# happens; only at the boundary do they become a claim with nothing behind it.
ANNOUNCE = re.compile(
    # NOT `-\s*` in the prefix: it matched the hyphen inside `long-running`
    # and fired on five turns across three projects that never announced
    # anything. Em-dash is a real clause lead; hyphen is part of a word.
    # `;` joins two independent clauses, so it ends a claim the way a full stop does.
    # `:` does NOT: it labels what follows, and `Background: Running the sweep in eight
    # shards.` is a report on work already running -- the same carve-out the participle
    # arm makes for `Continuing to wait`. A colon-led announcement is therefore out of
    # scope and said so below, rather than bought at the price of that shape.
    # `--` as well as the em dash: it is this repository's own spelling for one, in every
    # context file and commit message, and only the typographic character was modelled.
    r'(?:^|[.!?;\n]\s*|—\s*|--\s+)'
    r'(?:'
    # The participle must lead into an OBJECT — "Starting the audit",
    # "Continuing with the merge class". `Continuing to wait/collect/hold` is a
    # description of an ongoing state, usually while background agents run, and
    # ending the turn there is correct. That distinction is 4 of the 10 false
    # positives measured across 696 transcripts.
    r'(?:Starting|Running|Proceeding|Continuing|Beginning|Kicking off|Firing off)'
    r'\s+(?:with|on|the|a|an)\b'
    r'|(?:Let me|Let\'s)\s+(?:now\s+|go\s+ahead\s+and\s+)?'
    r'(?:start|run|check|look|do|go|build|fix|verify|audit|dig|pull|open|read|grep|sweep|write|take)'
    # `I'll <verb>` REQUIRES an imminence marker. Bare "I'll verify X" is far
    # more often a standing policy or a sequencing note than a claim to be
    # acting now — measured on real transcripts, that arm produced 3 of 4 false
    # positives ("I'll verify each agent's sharpest claim myself, as before").
    # The present participles carry the failure on their own.
    r'|I\'?ll\s+(?:now|go\s+ahead\s+and)\s+'
    r'(?:start|run|check|look|do|build|fix|verify|audit|dig|pull|open|read|write|kick|take)'
    r'|(?:On it|Doing that now|Running that now|Starting now|Working on it)\b'
    r')',
    re.I)

# Legitimate ways to end a turn. These must never be blocked: handing the
# decision back is the correct move, and gating it would push the model toward
# acting without approval - the opposite failure, and a worse one.
# A participle clause whose sentence goes on to REPORT is narration of work that ran, not
# a claim that it is about to. `Running the sweep completed in 4m.` is the same opening
# words as the failure this blocks and the opposite meaning, and the decoration strip put
# that shape in reach for the first time. Matched only against the REST of the unit the
# trigger was found in, so a report in the following sentence cannot excuse an
# announcement in this one.
REPORT_TERMS = frozenset({
    "completed", "finished", "took", "landed", "ran", "passed", "failed",
    "produced", "returned", "wrote", "reproduced", "stayed", "showed", "found",
})

# A completed-work token is evidence only when it is the predicate of the activity that
# ANNOUNCE matched. The participle arm can form that grammatical subject; "Let me", "I'll"
# and the fixed-form arms cannot. Clause boundaries stop the association, so a prior run's
# result in "Starting the audit because the previous run failed" cannot excuse the new
# announcement. This remains an explicit English heuristic, not a general parser.
# The participle check is load-bearing: "Let me verify the checks passed earlier" has a
# completed-work token, a result tail, and no clause break, yet reports nothing about the
# proposed verification. Interrogative complements are also clause breaks, so they cannot
# be the shape that grades this test.
