def report_separator_breaks(separator, following_word):
    """Return whether text between two semantic tokens ends the activity clause."""
    if any(mark in separator for mark in (";", "!", "?", "—")):
        return True
    # Repository-style `` -- `` is a clause dash; an attached ``--verbose`` is not.
    if re.search(r'(?:^|\s)--(?=\s)', separator):
        return True
    if "," in separator:
        return True
    if "." in separator:
        # Whitespace/decorated stops and no-space sentence starts are boundaries. Dots
        # inside versions, URLs and paths retain a lowercase or numeric next token.
        after = separator.rsplit(".", 1)[1]
        if any(char.isspace() for char in after) or following_word[:1].isupper():
            return True
    if ":" in separator:
        after = separator.rsplit(":", 1)[1]
        decorated = after[:1] in "*_\"'“”‘’`([{<"
        separated = bool(after) and (after[0].isspace() or decorated)
        if separated and following_word.casefold() not in REPORT_TERMS:
            return True
    return False


def colon_label_pending(separator, following_word):
    """Return whether a colon label withheld its break only for a following report term.

    The exemption exists for the direct predicate -- ``Starting the audit: completed in
    4m.`` -- and for nothing else. The caller applies the withheld break unless that exact
    token resolves as the activity's predicate: without this, one report term after a
    colon label disarmed the break for the whole remainder, and a later report excused
    ``Starting the audit: failed checks were found earlier.`` Derived from the classifier
    itself with a probe word of matching case, so the two can never parse a colon
    differently.
    """
    if ":" not in separator or report_separator_breaks(separator, following_word):
        return False
    probe = "X" if following_word[:1].isupper() else "x"
    return report_separator_breaks(separator, probe)


def comma_subject_is_clear(core_words):
    """Return whether the pre-report tail has an activity-noun shape."""
    if not core_words:
        return False
    head = core_words[-1]
    # Surface text cannot generally distinguish a noun from an adjective. Only explicit
    # activity nouns are sufficient evidence; possessives, platform names and unknown
    # singular or plural heads block for one turn rather than excusing work that never ran.
    return head in REPORT_ACTIVITY_HEADS


def report_group_separator(separator, group_stack):
    """Return outside text and whether a complete outer group closed in this separator."""
    outside = []
    outer_group_closed = False
    index = 0
    while index < len(separator):
        character = separator[index]
        if (character == "\\" and index + 1 < len(separator)
                and separator[index + 1] in REPORT_GROUP_ESCAPES):
            # Markdown-style escapes make a delimiter literal. Omit both bytes from the
            # semantic separator so the escaped punctuation can neither open/close a group
            # nor become an outer clause boundary.
            index += 2
            continue
        if character == "`":
            end = index + 1
            while end < len(separator) and separator[end] == "`":
                end += 1
            run = separator[index:end]
            if group_stack and group_stack[-1] == run:
                group_stack.pop()
                if not group_stack:
                    outer_group_closed = True
            elif not group_stack or not group_stack[-1].startswith("`"):
                group_stack.append(run)
            index = end
            continue
        if group_stack:
            if character == group_stack[-1]:
                group_stack.pop()
                if not group_stack:
                    outer_group_closed = True
            elif character in REPORT_GROUP_PAIRS:
                group_stack.append(REPORT_GROUP_PAIRS[character])
        elif character in REPORT_GROUP_PAIRS:
            group_stack.append(REPORT_GROUP_PAIRS[character])
        else:
            outside.append(character)
        index += 1
    return "".join(outside), outer_group_closed


def report_group_names_historical_activity(words):
    """Return whether a closed group clearly names a different, earlier activity."""
    if not words:
        return False

    def historical_compound(word):
        parts = word.split("-")
        return (len(parts) == 2 and parts[0] in REPORT_HISTORICAL_SUBJECT_MARKERS
                and parts[1] in REPORT_ACTIVITY_HEADS)

    first = words[0]
    if (first not in REPORT_GROUP_SUBJECT_LEADS
            and first not in REPORT_GROUP_TEMPORAL_POSSESSIVES
            and not (first.endswith("'s") and first != "today's")
            and not historical_compound(first)):
        return False

    def activity_base(word):
        return word[:-2] if word.endswith("'s") else word

    activity_indexes = [
        index for index, word in enumerate(words)
        if activity_base(word) in REPORT_ACTIVITY_HEADS or historical_compound(word)
    ]
    if not activity_indexes:
        return False
    # The rightmost activity token is the grouped noun phrase's head in every supported
    # shape (``integration test case``, ``workflow run attempt``). Considering every
    # earlier activity token rebuilt overlapping prefixes and made one long group cubic.
    index = activity_indexes[-1]
    word = words[index]
    prefix = words[:index]
    tail = words[index + 1:]
    if not REPORT_GROUP_NONSUBJECT_LINKS.isdisjoint(prefix):
        return False

    marker_cursor = len(prefix) - 1
    while (marker_cursor >= 0
           and prefix[marker_cursor] in REPORT_GROUP_ACTIVITY_MODIFIERS):
        marker_cursor -= 1
    marker_scopes_activity = (
        bool(prefix) and prefix[-1] in REPORT_HISTORICAL_SUBJECT_MARKERS
    ) or (
        marker_cursor >= 0 and prefix[marker_cursor] in {"previous", "prior"}
    ) or (
        len(prefix) >= 2 and prefix[-2] == "last" and prefix[-1].endswith("'s")
        and prefix[-1][:-2] in REPORT_GROUP_TIME_UNITS
    )
    distinct_quantifier = any(
        item in {"another", "different", "other"} for item in prefix
    )
    historical = (historical_compound(word) or marker_scopes_activity
                  or not REPORT_GROUP_TEMPORAL_POSSESSIVES.isdisjoint(prefix)
                  or distinct_quantifier)

    def temporal_length(items, start=0):
        if start >= len(items):
            return 0
        if items[start] in REPORT_GROUP_WEEKDAYS:
            return 1
        if items[start] in REPORT_GROUP_SUBJECT_TAILS:
            return (2 if start + 1 < len(items)
                    and items[start + 1] in {"morning", "afternoon", "evening", "night"}
                    else 1)
        if start + 1 < len(items) and items[start] == "last" and items[start + 1] in (
                REPORT_GROUP_TIME_UNITS | {"night"}):
            return 2
        if (start + 2 < len(items)
                and (items[start] in REPORT_GROUP_TIME_COUNTS or items[start].isdigit())
                and items[start + 1] in REPORT_GROUP_TIME_UNITS
                and items[start + 2] == "ago"):
            return 3
        return 0

    tail_time = temporal_length(tail)
    from_time = (len(tail) > 1 and tail[0] == "from"
                 and temporal_length(tail, 1) > 0)
    if not historical and not tail_time and not from_time:
        return False

    tail_index = 0
    while tail_index < len(tail):
        current = tail[tail_index]
        if current in REPORT_GROUP_SUBJECT_NOUN_TAILS:
            tail_index += 1
            continue
        length = temporal_length(tail, tail_index)
        if length:
            tail_index += length
            continue
        if current == "from":
            length = temporal_length(tail, tail_index + 1)
            if not length:
                if (tail_index + 1 >= len(tail)
                        or tail[tail_index + 1] not in REPORT_GROUP_SUBJECT_CONTEXTS["from"]):
                    break
                length = 1
            tail_index += length + 1
            continue
        if current in REPORT_POSTGROUP_CONTEXTS:
            if (tail_index + 1 >= len(tail)
                    or tail[tail_index + 1] not in REPORT_POSTGROUP_CONTEXTS[current]):
                break
            tail_index += 2
            continue
        if current in {"after", "before"}:
            tail_index += 1
            if tail_index < len(tail) and tail[tail_index] in {"a", "an", "the"}:
                tail_index += 1
            if tail_index >= len(tail):
                break
            tail_index += 1
            continue
        if current == "at" and tail_index + 1 < len(tail):
            tail_index += 2
            continue
        break
    return tail_index == len(tail)


def adjectival_report_is_predicate(remainder, report_end, core_words):
    """Return whether an adjectival report token has a predicate-shaped continuation."""
    if REPORT_RESULT_TAIL.match(remainder, report_end):
        # A group opener is also a valid result tail (``sweep failed (three errors)``),
        # but after an unknown/count head it can instead modify a later activity noun:
        # ``three failed (quarantined) tests``. Require the activity head before treating
        # this ambiguous spelling as a predicate; the outer parser can then resume at
        # ``tests`` and still accept a later direct predicate.
        if report_group_follows(remainder, report_end):
            return comma_subject_is_clear(core_words)
        return True
    comma = REPORT_COMMA_TAIL.match(remainder, report_end)
    if not comma:
        return False
    # Once a comma begins, its following phrase cannot reliably reveal whether the report
    # word was a predicate (``returning errors``) or another prenominal modifier
    # (``quarantined in CI tests``). Require the evidence before the report instead.
    return comma_subject_is_clear(core_words)


def report_group_follows(remainder, position):
    """Return whether the next undecorated character opens a supported group."""
    while position < len(remainder) and remainder[position] in " \t\r\n*_":
        position += 1
    if position >= len(remainder) or remainder[position] == "\\":
        return False
    return remainder[position] == "`" or remainder[position] in REPORT_GROUP_PAIRS


def soft_colon_predicate_bridge(separator, core_last, core_incomplete):
    """Return whether a same-line colon may defer a complete activity's predicate."""
    return ("\r" not in separator and "\n" not in separator
            and core_last is not None and core_last not in REPORT_NONFINAL
            and not core_incomplete and colon_label_pending(separator, "failed"))


def reports_this_activity(unit, found):
    """Return whether a direct completed-work predicate belongs to ``found``.

    One pass, linear in the unit. Whole semantic tokens carry report, complement and
    activity-word meaning; separators carry punctuation meaning. Advancing both together
    avoids growing-prefix rescans and prevents a slash/hyphen fragment from changing roles
    merely because another activity noun appeared before it.
    """
    if not PARTICIPLE_ANNOUNCEMENT.search(found.group(0)):
        return False
    remainder = unit[found.end():]
    core_last = None          # last non-modifier token ending at or before the report
    core_words = []           # non-structural tokens preceding a report adjective
    core_incomplete = False   # an INCOMPLETE token seen among those
    previous_end = 0
    previous_word = None
    url_active = False
    group_stack = []
    group_words = []
    grouped_historical_subject = False
    after_group = False
    adjectival_group_modifier = False
    colon_adjectival_candidate = False
    colon_pending = False
    context_preposition = None
    for token in REPORT_TOKEN.finditer(remainder):
        original_word = token.group(0)
        word = original_word.casefold()
        separator = remainder[previous_end:token.start()]
        url_was_active = url_active
        if any(char.isspace() for char in separator):
            url_active = False
        if previous_word in {"http", "https"} and "://" in separator:
            url_active = True
        outside_separator = separator
        if not url_active:
            if url_was_active:
                # URL punctuation before the first whitespace stays locator content,
                # except a trailing run of sentence punctuation against that whitespace,
                # which is prose the way GFM autolinks read it: ``https://x.test, failed``
                # ends the locator at the comma. A closing quote/backtick inside the
                # locator must not become a new prose opener merely because the following
                # token is outside the URL.
                cut = next(index for index, character in enumerate(separator)
                           if character.isspace())
                locator = separator[:cut]
                prose_tail = len(locator) - len(locator.rstrip(".,;:!?"))
                separator = separator[cut - prose_tail:]
            was_in_group = bool(group_stack)
            outside_separator, outer_group_closed = report_group_separator(
                separator, group_stack)
            if not was_in_group and group_stack:
                group_words = []
            if outer_group_closed:
                grouped_historical_subject = (
                    grouped_historical_subject
                    or report_group_names_historical_activity(group_words))
                group_words = []
                after_group = True
        if not url_active and group_stack:
            # An outside break mark before this group's opener ends the activity clause
            # even though the group is open: the em dash in ``sweep — (nightly)`` is
            # outer prose, and an in-group separator carries no outside text, so this
            # fires only on what precedes the opener. A pending colon label also stands,
            # because a token inside an aside cannot be the activity's direct predicate.
            group_colon = soft_colon_predicate_bridge(
                outside_separator, core_last, core_incomplete)
            if report_separator_breaks(outside_separator, original_word) and not group_colon:
                return False
            if colon_label_pending(outside_separator, original_word) and not group_colon:
                return False
            # Tokens inside an aside cannot replace the announced activity's subject or
            # provide its completed-work predicate. Once the group closes, the next token
            # resumes against the outer subject accumulated before the opener.
            # A straight single closing quote is part of REPORT_TOKEN (for contractions
            # and possessives), so consume it from the token. The post-group rule below
            # prevents a following noun from replacing the outer activity subject.
            group_words.append(word.strip("'"))
            if group_stack[-1] == "'" and original_word.endswith("'"):
                group_stack.pop()
                if not group_stack:
                    grouped_historical_subject = (
                        grouped_historical_subject
                        or report_group_names_historical_activity(group_words))
                    group_words = []
                    after_group = True
            previous_word = word
            previous_end = token.end()
            continue
        colon_bridge = (not url_active
                        and soft_colon_predicate_bridge(
                            outside_separator, core_last, core_incomplete)
                        and (word in REPORT_POSTGROUP_MODIFIERS
                             or word in REPORT_POSTGROUP_CONTEXTS))
        if (not url_active
                and report_separator_breaks(outside_separator, original_word)
                and not colon_bridge):
            if colon_adjectival_candidate and after_group:
                return True
            return False
        if colon_bridge:
            colon_pending = True
        pending_colon = (colon_pending or (not url_active
                         and colon_label_pending(outside_separator, original_word)))
        if url_active:
            # Locator tokens are neither clause words nor completed-work predicates.
            # Only the first whitespace-bearing separator releases prose parsing.
            previous_word = word
            previous_end = token.end()
            continue
        if (colon_adjectival_candidate and after_group
                and word in REPORT_POSTGROUP_RESULT_TAILS):
            return True
        if word in REPORT_CLAUSE_WORDS:
            return False
        bridge_active = after_group or colon_pending
        if context_preposition is not None:
            if word not in REPORT_POSTGROUP_CONTEXTS[context_preposition]:
                return False
            context_preposition = None
            previous_word = word
            previous_end = token.end()
            continue
        if bridge_active and word not in REPORT_TERMS:
            if word in REPORT_POSTGROUP_MODIFIERS:
                previous_word = word
                previous_end = token.end()
                continue
            if word in REPORT_POSTGROUP_CONTEXTS:
                context_preposition = word
                previous_word = word
                previous_end = token.end()
                continue
            if adjectival_group_modifier:
                # The group modified an earlier adjective, not the announced subject.
                # Resume ordinary subject parsing at the following noun so a later direct
                # predicate can still prove that the announced activity ran.
                after_group = False
                adjectival_group_modifier = False
                grouped_historical_subject = False
            else:
                return False
        if word in REPORT_TERMS:
            if grouped_historical_subject:
                return False
            if core_last is None or core_last in REPORT_NONFINAL or core_incomplete:
                if pending_colon:
                    return False
                previous_end = token.end()
                continue
            grouped_adjective = (word in REPORT_ADJECTIVAL
                                 and report_group_follows(remainder, token.end()))
            adjectival_predicate = (word in REPORT_ADJECTIVAL
                                    and adjectival_report_is_predicate(
                                        remainder, token.end(), core_words))
            if grouped_adjective and pending_colon and adjectival_predicate:
                colon_adjectival_candidate = True
                previous_end = token.end()
                continue
            if word in REPORT_ADJECTIVAL and not adjectival_predicate:
                if pending_colon:
                    return False
                if report_group_follows(remainder, token.end()):
                    adjectival_group_modifier = True
                previous_end = token.end()
                continue
            return True
        if word not in REPORT_MODIFIERS:
            # A determiner is inside ANNOUNCE, so the remainder must still name an
            # activity. This rejects "Starting the failed audit" and "Starting the
            # already completed audit"; a dangling preposition rejects "Starting the
            # audit for failed checks".
            core_last = word
            core_incomplete = core_incomplete or word in REPORT_INCOMPLETE
            if word not in REPORT_NONFINAL and word not in REPORT_INCOMPLETE:
                core_words.append(word)
        previous_word = word
        previous_end = token.end()
    if colon_adjectival_candidate:
        _, trailing_group_closed = report_group_separator(
            remainder[previous_end:], group_stack)
        return not group_stack and (after_group or trailing_group_closed)
    return False

HANDBACK = re.compile(
    r'(stopping here|stopped here|say go|your call|let me know|over to you|'
    r'waiting on|want me to|shall I|should I|do you want|which (would|do) you|'
    r'before I (start|proceed|continue|touch|change)|say the word|'
    r'happy to .{0,30}if you|unless you|if you\'d rather|continuing to (wait|collect|hold|monitor|poll|watch))', re.I)

# The boundary is the LAST SENTENCE OR TWO, not a character window. A window
# was the first design and its own control caught it: on a short message the
# window is the whole message, so "Let me check the register. …I checked it:
# 47 markers. Committed d5e1a26." blocked - an announcement that was narration
# of work the same message then reported doing. Position in the message is the
# whole discriminator, so it has to be measured in sentences.
TAIL_UNITS = 2

# Structural blocks are identified before sentence splitting. Each table row, heading,
# list item or paragraph supplies units; a fenced code block supplies exactly ONE unit,
# regardless of delimiter type, content punctuation or the presence of a closing line.
# Shown material still occupies tail slots, but cannot announce work. Code also cannot
# supply a handback. Inline emphasis is decoration, not a structural container.
SENTENCE_END = re.compile(r'(?<=[.!?])\s+')
EMPHASIS = re.compile(r'^(?:\*\*|__|\*|_)+')
QUOTE_LEAD = re.compile(r'^(?: {0,3}>[ \t]?)+')
QUOTE_MARKER = re.compile(r' {0,3}>[ \t]?')
LIST_LEAD = re.compile(r'^[ \t]*(?:[-+*]|\d+[.)])[ \t]+')
ATX_HEADING = re.compile(r'^[ \t]*#{1,6}(?=[ \t]|$)')
FENCE_LINE = re.compile(r'^ {0,3}(`{3,}|~{3,})(.*)$')


def markdown_blocks(text):
    """Yield the supported physical block spans as (text, code, container).

    Quote/list paragraphs admit marked, indented and lazy continuation lines; ATX
    headings and table rows end at their physical line. Blank lines end lazy continuation.
    List indentation can retain a following paragraph. A fence closes only on a matching
    kind, sufficient length and whitespace-only suffix, or at its containing block's end.
    This is a bounded block classifier, not a full Markdown parser: setext headings, HTML
    blocks, thematic breaks and standalone indented code are not classified here.
    """
    lines, kind = [], "prose"
    paragraph = False
    list_indent = 0
    fence = None

    def take():
        nonlocal lines
        block = "\n".join(lines)
        lines = []
        return block, kind == "code", kind != "prose"

    for raw in text.split("\n"):
        # CRLF framing is not a fence suffix. Keep the original block text unchanged.
        line = (raw[:-1] if raw.endswith("\r") else raw).expandtabs(4)
        quote = QUOTE_LEAD.match(line)
        depth = quote.group(0).count(">") if quote else 0
        content = line[quote.end():] if quote else line
        indent = len(content) - len(content.lstrip(" "))
        if fence:
            delimiter, length, quote_depth, fence_indent = fence
            offset = 0
            for _ in range(quote_depth):
                prefix = QUOTE_MARKER.match(line, offset)
                if not prefix:
                    break
                offset = prefix.end()
            # Strip only the opener's container prefix. Extra `>` characters inside code
            # are literal content, not a new quote whose marker can reveal a closer.
            content = line[offset:]
            indent = len(content) - len(content.lstrip(" "))
            if (depth < quote_depth
                    or (fence_indent and content.strip() and indent < fence_indent)):
                yield take()
                fence = None
                paragraph, list_indent = False, 0
            else:
                lines.append(raw)
                closer = FENCE_LINE.match(content[fence_indent:])
                if (closer and closer.group(1)[0] == delimiter
                        and len(closer.group(1)) >= length
                        and not closer.group(2).strip(" \t")):
                    yield take()
                    fence = None
                continue
        if not line.strip():
            if lines:
                yield take()
            paragraph = False
            continue

        indented_item = bool(list_indent and indent >= list_indent)
        if indented_item:
            content = content[list_indent:]
        item = LIST_LEAD.match(content)
        if item:
            list_indent = (list_indent if indented_item else 0) + item.end()
            content = content[item.end():]
            next_kind = "list"
        elif depth or indented_item:
            next_kind = "list" if indented_item else "quote"
        elif paragraph and kind in ("quote", "list"):
            next_kind = kind
        else:
            next_kind, list_indent = "prose", 0

        marker = FENCE_LINE.match(content)
        if marker and (marker.group(1)[0] != "`" or "`" not in marker.group(2)):
            if lines:
                yield take()
            kind, lines = "code", [raw]
            fence = (marker.group(1)[0], len(marker.group(1)), depth,
                     list_indent if item or indented_item else 0)
            paragraph = False
            continue
        if ATX_HEADING.match(content) or content.lstrip().startswith("|"):
            if lines:
                yield take()
            kind, lines = "container", [raw]
            yield take()
            paragraph = False
            if not item and not indented_item:
                list_indent = 0
            continue
        if item or kind != next_kind or not content.strip():
            if lines:
                yield take()
        kind = next_kind
        lines.append(raw)
        paragraph = bool(content.strip())
    if lines:
        yield take()


def boundary(text):
    """The last TAIL_UNITS units as (text, is_code, is_container).

    Work policy: classify physical lines once, split each non-code block once, and retain
    only two units. No sentence rescans or copies its growing physical-line prefix; no
    tail truncation can discard an earlier fence opener. The scale selftest checks this
    progress property separately from the actual-stdin five-second runtime probe.
    """
    parts = deque(maxlen=TAIL_UNITS)

    def append(part, container):
        unit = part.strip()
        if not container:
            unit = EMPHASIS.sub("", unit).strip()
        if unit:
            parts.append((unit, False, container))

    for block, code, container in markdown_blocks(text):
        if code:
            parts.append((block, True, container))
            continue
        cursor = 0
        for separator in SENTENCE_END.finditer(block):
            append(block[cursor:separator.start()], container)
            cursor = separator.end()
        append(block[cursor:], container)
    return list(parts)


